-- DBTITLE 1,Step 2 — Upsert td_resource
-- Merge key: (account_cd, workspace_cd, source_cd, resource_type_lb) — same key the old
-- apply_changes() used, so resource_id stays stable across the DLT-to-MERGE migration.
-- resource_id is Delta GENERATED BY DEFAULT AS IDENTITY — omitted from INSERT, auto-assigned
-- for new rows; preserved on UPDATE by never being written to.
MERGE INTO global_it_hub.td_resource AS tgt
USING v_resource_union AS src
  ON  tgt.account_cd       = src.account_cd
  AND tgt.workspace_cd     = src.workspace_cd
  AND tgt.source_cd        = src.source_cd
  AND tgt.resource_type_lb = src.resource_type_lb
WHEN MATCHED AND (
     tgt.region_lb        IS DISTINCT FROM src.region_lb
  OR tgt.display_name_lb  IS DISTINCT FROM src.display_name_lb
  OR tgt.owned_by_cd      IS DISTINCT FROM src.owned_by_cd
  OR tgt.is_active_fl     IS DISTINCT FROM src.is_active_fl
) THEN UPDATE SET
  tgt.region_lb       = src.region_lb,
  tgt.display_name_lb = src.display_name_lb,
  tgt.owned_by_cd     = src.owned_by_cd,
  tgt.is_active_fl    = src.is_active_fl,
  tgt.sys_update_dt   = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT (
  resource_type_lb, source_cd, account_cd, region_lb, workspace_cd,
  display_name_lb, owned_by_cd, is_active_fl, sys_create_dt, sys_update_dt
) VALUES (
  src.resource_type_lb, src.source_cd, src.account_cd, src.region_lb, src.workspace_cd,
  src.display_name_lb, src.owned_by_cd, src.is_active_fl, CURRENT_TIMESTAMP(), CURRENT_TIMESTAMP()
);
