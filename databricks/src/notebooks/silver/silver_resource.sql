-- MAGIC
-- MAGIC Builds `td_resource` — one row per billable resource (job, pipeline, cluster, warehouse,
-- MAGIC app, notebook, endpoint, networking client, data quality monitoring schema) — from a
-- MAGIC `UNION ALL` of 11 branches (ENDPOINT resources come from two source tables,
-- MAGIC `td_serving_entity` and `td_billing_endpoint`, deduplicated — see below).
-- MAGIC
-- MAGIC **Not DLT-managed** — moved off `apply_changes()`/streaming (`silver_dimensions.py`)
-- MAGIC because every source table (`td_lakeflow_job`, `td_compute_warehouse`,
-- MAGIC `td_lakeflow_pipeline`, `td_compute_cluster`, `td_billing_app`, `td_billing_notebook`,
-- MAGIC `td_billing_endpoint`, `td_billing_network`, `td_billing_data_quality_monitoring`,
-- MAGIC `td_serving_entity`) is itself
-- MAGIC `apply_changes()`-managed (SCD1) and receives row-level UPDATEs whenever an attribute
-- MAGIC changes — not append-only. A streaming read of an upserted table fails with
-- MAGIC `DELTA_SOURCE_TABLE_IGNORE_CHANGES` the moment any row is updated; the only
-- MAGIC streaming-safe workaround (`skipChangeCommits`) would silently drop every such update
-- MAGIC forever, leaving `td_resource` permanently stale. Same reasoning as
-- MAGIC `td_workspace`/`td_billing_list_price`/`td_identity`.
-- MAGIC
-- MAGIC | Source | Target |
-- MAGIC |---|---|
-- MAGIC | 11 silver dimension tables (`UNION ALL`) | `global_it_hub.td_resource` |
-- MAGIC
-- MAGIC **Prerequisites**: run the silver DLT pipeline first — all 11 source tables must be
-- MAGIC populated.
-- MAGIC
-- MAGIC ### Processing strategy
-- MAGIC No watermark: every run re-reads all 11 source tables in full (each is already a small
-- MAGIC current-state SCD1 dimension, not a growing fact table — cheap to rescan) and MERGEs
-- MAGIC into `td_resource`. `resource_id` is preserved on UPDATE (Delta `GENERATED BY DEFAULT AS
-- MAGIC IDENTITY`, omitted from the INSERT column list — auto-assigned only for genuinely new
-- MAGIC resources). `is_active_fl` mirrors each source's `is_deleted_fl` where available (jobs,
-- MAGIC warehouses, pipelines, clusters, and now the `td_serving_entity` branch of ENDPOINT);
-- MAGIC billing dimensions without a deletion concept upstream (apps, notebooks, the
-- MAGIC `td_billing_endpoint` fallback branch of ENDPOINT, networking, data quality monitoring,
-- MAGIC predictive optimization) are always active.
-- MAGIC
-- MAGIC **ENDPOINT resources come from two sources, deduplicated by `endpoint_cd`**:
-- MAGIC `td_serving_entity` (richer — real `region_lb`/`is_deleted_fl`, from
-- MAGIC `system.serving.served_entities`, collapsed from served-entity grain to endpoint grain
-- MAGIC with `QUALIFY ROW_NUMBER() ... ORDER BY change_time DESC = 1`) is the primary source;
-- MAGIC `td_billing_endpoint` (from billing usage) only contributes an endpoint via `NOT EXISTS`
-- MAGIC when `td_serving_entity` doesn't already have it — covers endpoints that generated
-- MAGIC billing usage but haven't (yet) appeared in the serving system table.
-- MAGIC
-- MAGIC Each branch filters `WHERE {entity}_id > 0` to exclude the -2/-1 sentinel rows
-- MAGIC (Unassigned/Unknown) from each source dimension — `td_resource` has its own sentinel
-- MAGIC rows (inserted via `init_tables_silver.sql`) and must not union in the sources'.

