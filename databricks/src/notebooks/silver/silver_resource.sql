-- DBTITLE 1,Step 1 — Stage unified resource union (9 dimension tables)
-- UNION ALL matches columns by position, not name — every branch must list columns in the
-- exact same order. Referenced once (Step 2) — temp view, not materialized.
CREATE OR REPLACE TEMP VIEW v_resource_union AS

SELECT
  'JOB'              AS resource_type_lb,
  job_cd             AS source_cd,
  account_cd,
  region_lb,
  workspace_cd,
  job_name_lb        AS display_name_lb,
  creator_userid_cd  AS owned_by_cd,
  CASE WHEN is_deleted_fl = 0 THEN 1 ELSE 0 END AS is_active_fl
FROM global_it_hub.td_lakeflow_job
WHERE job_id > 0

UNION ALL

SELECT
  'WAREHOUSE'        AS resource_type_lb,
  warehouse_cd       AS source_cd,
  account_cd,
  region_lb,
  workspace_cd,
  warehouse_name_lb  AS display_name_lb,
  created_by_cd      AS owned_by_cd,
  CASE WHEN is_deleted_fl = 0 THEN 1 ELSE 0 END AS is_active_fl
FROM global_it_hub.td_compute_warehouse
WHERE warehouse_id > 0

UNION ALL

SELECT
  'PIPELINE'         AS resource_type_lb,
  pipeline_cd        AS source_cd,
  account_cd,
  region_lb,
  workspace_cd,
  pipeline_name_lb   AS display_name_lb,
  created_by_cd      AS owned_by_cd,
  CASE WHEN is_deleted_fl = 0 THEN 1 ELSE 0 END AS is_active_fl
FROM global_it_hub.td_lakeflow_pipeline
WHERE pipeline_id > 0

UNION ALL

SELECT
  'CLUSTER'          AS resource_type_lb,
  cluster_cd         AS source_cd,
  account_cd,
  region_lb,
  workspace_cd,
  cluster_name_lb    AS display_name_lb,
  owned_by_cd,
  CASE WHEN is_deleted_fl = 0 THEN 1 ELSE 0 END AS is_active_fl
FROM global_it_hub.td_compute_cluster
WHERE cluster_id > 0

UNION ALL

-- Billing dimensions have no region field (use 'global') and no deletion concept (always active).
SELECT
  'APP'              AS resource_type_lb,
  app_cd             AS source_cd,
  account_cd,
  'global'           AS region_lb,
  workspace_cd,
  app_name_lb        AS display_name_lb,
  run_as_cd          AS owned_by_cd,
  1                  AS is_active_fl
FROM global_it_hub.td_billing_app
WHERE app_id > 0

UNION ALL

SELECT
  'NOTEBOOK'         AS resource_type_lb,
  notebook_cd        AS source_cd,
  account_cd,
  'global'           AS region_lb,
  workspace_cd,
  notebook_path_lb   AS display_name_lb,
  run_as_cd          AS owned_by_cd,
  1                  AS is_active_fl
FROM global_it_hub.td_billing_notebook
WHERE notebook_id > 0

UNION ALL

-- Primary source of ENDPOINT resources: td_serving_entity (system.serving.served_entities)
-- collapsed from served-entity grain to endpoint grain — has a real region_lb and
-- is_deleted_fl, unlike td_billing_endpoint. QUALIFY keeps only the most recently changed
-- served entity per endpoint; region_lb/is_deleted_fl are genuinely endpoint-level fields
-- (uniform across every served entity of that endpoint), so picking any one row is safe.
SELECT
  'ENDPOINT'         AS resource_type_lb,
  endpoint_cd        AS source_cd,
  account_cd,
  region_lb,
  workspace_cd,
  endpoint_name_lb   AS display_name_lb,
  created_by_cd      AS owned_by_cd,
  CASE WHEN is_deleted_fl = 0 THEN 1 ELSE 0 END AS is_active_fl
FROM global_it_hub.td_serving_entity
WHERE entity_id > 0
QUALIFY ROW_NUMBER() OVER (
  PARTITION BY account_cd, workspace_cd, endpoint_cd
  ORDER BY change_time DESC
) = 1

UNION ALL

-- Fallback source of ENDPOINT resources: td_billing_endpoint only contributes endpoints not
-- already captured by td_serving_entity (e.g. endpoints with billing usage but not yet seen
-- by system.serving.served_entities) — avoids duplicate ENDPOINT rows for the same endpoint_cd.
SELECT
  'ENDPOINT'         AS resource_type_lb,
  t1.endpoint_cd     AS source_cd,
  t1.account_cd,
  'global'           AS region_lb,
  t1.workspace_cd,
  t1.endpoint_name_lb AS display_name_lb,
  t1.run_as_cd       AS owned_by_cd,
  1                  AS is_active_fl
FROM global_it_hub.td_billing_endpoint AS t1
WHERE t1.endpoint_id > 0
  AND NOT EXISTS (
    SELECT 1
    FROM global_it_hub.td_serving_entity AS t2
    WHERE t2.entity_id     > 0
      AND t2.account_cd    = t1.account_cd
      AND t2.workspace_cd  = t1.workspace_cd
      AND t2.endpoint_cd   = t1.endpoint_cd
  )

UNION ALL

SELECT
  'NETWORKING'       AS resource_type_lb,
  network_client_cd  AS source_cd,
  account_cd,
  'global'           AS region_lb,
  workspace_cd,
  network_client_cd  AS display_name_lb,
  run_as_cd          AS owned_by_cd,
  1                  AS is_active_fl
FROM global_it_hub.td_billing_network
WHERE network_id > 0

UNION ALL

SELECT
  'DATA QUALITY MONITORING' AS resource_type_lb,
  dqm_cd             AS source_cd,
  account_cd,
  'global'           AS region_lb,
  workspace_cd,
  dqm_cd             AS display_name_lb,
  created_by_cd      AS owned_by_cd,
  1                  AS is_active_fl
FROM global_it_hub.td_billing_data_quality_monitoring
WHERE dqm_id > 0

UNION ALL
SELECT
  'PREDICTIVE OPTIMIZATION' AS resource_type_lb,
  'PREDICTIVE_OPTIMIZATION' AS source_cd,
  account_cd,
  'global'           AS region_lb,
  workspace_cd,
  'Predictive Optimization'  AS display_name_lb,
  'System-User'      AS owned_by_cd,
  1                  AS is_active_fl
FROM global_it_hub.td_workspace
WHERE workspace_id > 0;

