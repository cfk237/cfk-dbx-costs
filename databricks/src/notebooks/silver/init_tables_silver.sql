  region_lb        STRING    COMMENT 'Databricks region (e.g. eastus, westeurope).',
  workspace_cd     STRING    NOT NULL COMMENT 'Workspace ID the resource belongs to.',
  display_name_lb  STRING    COMMENT 'Resource display name.',
  owned_by_cd      STRING    COMMENT 'User or service principal ID that owns the resource.',
  is_active_fl     INT       COMMENT 'Flag: 1 if the resource is active, 0 otherwise.',
  -- Audit
  sys_create_dt    TIMESTAMP NOT NULL COMMENT 'When this row was first inserted',
  sys_update_dt    TIMESTAMP NOT NULL COMMENT 'When this row was last updated'
)
USING DELTA
COMMENT 'Unified resource dimension. One row per billable resource.'
