-- DBTITLE 1,tf_billing_cost
-- Silver fact table joining billing usage with list prices. One row per billing record.
-- Sourced from tf_billing_usage (silver) enriched with cost in USD from system.billing.list_prices.
-- Cluster by ingestion_dt — matches tf_billing_usage partitioning for efficient MERGE.
CREATE TABLE IF NOT EXISTS global_it_hub.tf_billing_cost (
  record_cd        STRING              NOT NULL COMMENT 'Unique billing record identifier (source: record_id)',
