  product_lb          STRING                       COMMENT 'Billing origin product: JOBS, DLT, SQL, etc.',
  usage_type_lb       STRING                       COMMENT 'Usage category: COMPUTE_TIME, STORAGE_SPACE, etc.',
  sku_name_lb         STRING                       COMMENT 'SKU name',
  cloud_lb            STRING                       COMMENT 'Cloud provider: AWS, AZURE, or GCP',
